import type { LoadedRegistry } from "./index";

/** A registry item's `css` field: declarations (string values) and nested rules. */
export interface CssTree {
  [key: string]: string | CssTree;
}

export interface ThemeCssSource {
  cssVars?: {
    theme?: Record<string, string>;
    light?: Record<string, string>;
    dark?: Record<string, string>;
  };
  css?: CssTree;
}

/** Repo-relative path of the generated stylesheet the docs app imports. */
export const THEME_CSS_PATH = "app/mangacn-theme.css";

export const THEME_ITEM_NAME = "theme";

export const THEME_CSS_HEADER =
  "/* Generated by scripts/gen-theme-css.ts from the registry item `theme`. Do not edit; run `pnpm gen:theme`. */";

const INDENT = "  ";

function varName(key: string): string {
  return `--${key.replace(/^--/, "")}`;
}

function renderVars(selector: string, vars: Record<string, string> | undefined): string | null {
  const entries = Object.entries(vars ?? {});
  if (entries.length === 0) return null;
  const body = entries.map(([key, value]) => `${INDENT}${varName(key)}: ${value};`).join("\n");
  return `${selector} {\n${body}\n}`;
}

function renderRule(key: string, value: unknown, depth: number): string {
  const pad = INDENT.repeat(depth);
  if (typeof value === "string") return `${pad}${key}: ${value};`;
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`Unsupported value for "${key}" in theme css: ${JSON.stringify(value)}`);
  }
  const children = Object.entries(value);
  if (children.length === 0) {
    // `{ "@apply x": {} }` and `{ "@import \"y\"": {} }` are statements, not blocks.
    return key.startsWith("@") ? `${pad}${key};` : `${pad}${key} {}`;
  }
  const body = children.map(([child, inner]) => renderRule(child, inner, depth + 1)).join("\n");
  return `${pad}${key} {\n${body}\n${pad}}`;
}

/**
 * Renders a registry item's `cssVars` and `css` the way `shadcn add` merges them into a
 * user's globals.css: `cssVars.theme` → `@theme inline`, `light` → `:root`, `dark` →
 * `.dark`, then every `css` rule verbatim. Key order follows the source object, so the
 * same item always renders to the same string.
 */
export function renderThemeCss(item: ThemeCssSource): string {
  const blocks = [
    renderVars("@theme inline", item.cssVars?.theme),
    renderVars(":root", item.cssVars?.light),
    renderVars(".dark", item.cssVars?.dark),
    ...Object.entries(item.css ?? {}).map(([key, value]) => renderRule(key, value, 0)),
  ].filter((block): block is string => block !== null);
  return `${blocks.join("\n\n")}\n`;
}

/** The full contents of `app/mangacn-theme.css` for the given registry. */
export function renderThemeCssFile(registry: LoadedRegistry, name = THEME_ITEM_NAME): string {
  const item = registry.items.find((entry) => entry.name === name);
  if (!item) throw new Error(`Registry item "${name}" not found`);
  return `${THEME_CSS_HEADER}\n\n${renderThemeCss(item as ThemeCssSource)}`;
}
