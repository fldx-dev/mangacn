import { readFileSync } from "node:fs";
import path from "node:path";
import { registryItemUrl } from "./index";
import {
  PRESET_ATTRIBUTE,
  PRESET_BASE_TOKENS,
  presetCssVars,
  THEME_PRESETS,
  type ThemeLook,
} from "./theme-presets";

/**
 * What `pnpm gen:theme` makes of the preset values files (Task 99): the `theme-<name>` items in
 * the theme catalog and the docs site's scoped stylesheet. Node only; the names live in
 * `./theme-presets`.
 *
 * Derivation: every shadcn token of the default theme (`--background`, `--primary`, `--muted`,
 * `--chart-1`, `--sidebar-*`, …) is a `var()` of a base colour, so a preset lists the eight base
 * colours per mode and the item copies the rest of the default theme's values unchanged. The
 * tokens follow the preset through those references; nothing else can change.
 */

/** Repo-relative folder of the values files. */
export const PRESETS_DIR = "registry/theme/presets";

/** Repo-relative path of the theme catalog the preset items are written into. */
export const THEME_CATALOG_PATH = "registry/theme/registry.json";

/** Repo-relative path of the docs site's preset stylesheet (gitignored, imported by globals.css). */
export const PRESETS_CSS_PATH = "app/mangacn-presets.css";

export const PRESETS_CSS_HEADER =
  "/* Generated by scripts/gen-theme-css.ts from registry/theme/presets/*.json, for the docs site only. Do not edit; run `pnpm gen:theme`. */";

type Vars = Record<string, string>;

/** A preset's values file. */
export interface PresetValues {
  name: string;
  title: string;
  description: string;
  light: Vars;
  dark: Vars;
}

/** The default theme item as the builder reads it. */
export interface DefaultTheme {
  name: string;
  type: string;
  categories?: string[];
  meta?: Record<string, unknown>;
  cssVars: { theme: Vars; light: Vars; dark: Vars };
}

/** A built preset item, in the key order it is written to the catalog. */
export interface PresetItem {
  name: string;
  type: "registry:theme";
  title: string;
  description: string;
  categories: string[];
  meta: { since: string; preset: string };
  docs: string;
  registryDependencies: string[];
  files: [];
  cssVars: { theme: Vars; light: Vars; dark: Vars };
}

/** The release that ships presets. */
const PRESETS_SINCE = "0.2.0";

/** Reads and checks one values file: a name matching its file, the eight base colours per mode. */
export function readPresetValues(file: string): PresetValues {
  const values = JSON.parse(readFileSync(file, "utf8")) as PresetValues;
  const expected = path.basename(file, ".json");
  if (values.name !== expected) {
    throw new Error(`${file}: "name" is "${values.name}", expected "${expected}"`);
  }
  for (const mode of ["light", "dark"] as const) {
    const keys = Object.keys(values[mode] ?? {});
    const wanted = [...PRESET_BASE_TOKENS];
    if (keys.join() !== wanted.join()) {
      throw new Error(`${file}: ${mode} must list exactly ${wanted.join(", ")} in that order`);
    }
    for (const [token, value] of Object.entries(values[mode])) {
      if (!/^oklch\([\d.]+ [\d.]+ [\d.]+\)$/.test(value)) {
        throw new Error(`${file}: ${mode} --${token} is not a plain oklch() value: ${value}`);
      }
    }
  }
  return values;
}

/** Every listed preset's values, in `THEME_PRESETS` order. */
export function loadPresets(rootDir = process.cwd()): PresetValues[] {
  return THEME_PRESETS.map((name) =>
    readPresetValues(path.join(rootDir, PRESETS_DIR, `${name}.json`)),
  );
}

/**
 * The `registry:theme` item for a preset. It declares the default theme by URL, so one add
 * installs the fonts, utilities and keyframes too, and the CLI merges the default's cssVars
 * first and the preset's over them (dependencies before dependents, shadcn 4.23).
 */
export function presetItem(theme: DefaultTheme, preset: PresetValues): PresetItem {
  const name = `theme-${preset.name}`;
  return {
    name,
    type: "registry:theme",
    title: `mangacn theme: ${preset.title}`,
    description: preset.description,
    categories: theme.categories ?? ["decoration"],
    meta: { since: PRESETS_SINCE, preset: preset.name },
    docs: `@mangacn/${name} brings @mangacn/theme by URL and gives its ink, paper, spot and tone values (light and dark) the ${preset.title.toLowerCase()} look. Added over an installed theme, the CLI rewrites the same variables in globals.css in place: one set of tokens, nothing duplicated. Add @mangacn/theme to go back.`,
    registryDependencies: [registryItemUrl(theme.name)],
    files: [],
    cssVars: { theme: { ...theme.cssVars.theme }, ...presetCssVars(theme.cssVars, preset) },
  };
}

/** Whether a catalog entry is a generated preset item. */
export function isPresetItem(item: { name: string; type?: string }): boolean {
  return item.type === "registry:theme" && item.name.startsWith("theme-");
}

interface CatalogDocument {
  items: { name: string; type?: string }[];
  [key: string]: unknown;
}

/** The default `theme` item of a parsed theme catalog. */
export function defaultThemeOf(catalog: CatalogDocument): DefaultTheme {
  const theme = catalog.items.find((item) => item.name === "theme");
  if (!theme) throw new Error(`${THEME_CATALOG_PATH} has no "theme" item`);
  return theme as unknown as DefaultTheme;
}

/**
 * The theme catalog's text with its preset items replaced by `presets` (appended after every other
 * item, in order), laid out as Biome formats it so `biome check` agrees with the generator.
 */
export function renderThemeCatalog(catalogText: string, presets: readonly PresetValues[]): string {
  const catalog = JSON.parse(catalogText) as CatalogDocument;
  const theme = defaultThemeOf(catalog);
  const items = [
    ...catalog.items.filter((item) => !isPresetItem(item)),
    ...presets.map((preset) => presetItem(theme, preset)),
  ];
  return `${formatJson({ ...catalog, items })}\n`;
}

/** Biome's line width (biome.json). */
const LINE_WIDTH = 100;

/**
 * JSON as Biome lays out this repo's catalogs: objects one key per line, empty ones `{}`; an
 * array of strings or numbers on one line while that line fits, else one entry per line.
 */
export function formatJson(value: unknown, indent = "", prefix = "", suffix = ""): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const flat = value.every((entry) => entry === null || typeof entry !== "object");
    if (flat) {
      const inline = `[${value.map((entry) => JSON.stringify(entry)).join(", ")}]`;
      if (indent.length + prefix.length + inline.length + suffix.length <= LINE_WIDTH)
        return inline;
    }
    const lines = value.map(
      (entry, index) =>
        `${inner}${formatJson(entry, inner, "", index < value.length - 1 ? "," : "")}`,
    );
    return `[\n${lines.join(",\n")}\n${indent}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return "{}";
  const lines = entries.map(([key, entry], index) => {
    const head = `${JSON.stringify(key)}: `;
    const tail = index < entries.length - 1 ? "," : "";
    return `${inner}${head}${formatJson(entry, inner, head, tail)}`;
  });
  return `{\n${lines.join(",\n")}\n${indent}}`;
}

function declarations(vars: Vars, indent: string): string {
  return Object.entries(vars)
    .map(([key, value]) => `${indent}--${key}: ${value};`)
    .join("\n");
}

/**
 * The docs site's preset stylesheet: each look's full light set under
 * `[data-theme-preset="<name>"]` and its dark set under `.dark` on the same element or an
 * ancestor. Every token is declared again, not only the base colours, so the derived tokens
 * resolve against the preset on any element, not only the root. The default look is scoped too,
 * so a region can show it inside a page in another look.
 */
export function renderPresetsCss(theme: DefaultTheme, presets: readonly PresetValues[]): string {
  const looks: { look: ThemeLook; light: Vars; dark: Vars }[] = [
    { look: "default", light: theme.cssVars.light, dark: theme.cssVars.dark },
    ...presets.map((preset) => {
      const item = presetItem(theme, preset);
      return { look: preset.name as ThemeLook, light: item.cssVars.light, dark: item.cssVars.dark };
    }),
  ];
  const blocks = looks.flatMap(({ look, light, dark }) => {
    const scope = `[${PRESET_ATTRIBUTE}="${look}"]`;
    return [
      `${scope} {\n${declarations(light, "  ")}\n}`,
      `.dark${scope},\n.dark ${scope} {\n${declarations(dark, "  ")}\n}`,
    ];
  });
  return `${PRESETS_CSS_HEADER}\n\n${blocks.join("\n\n")}\n`;
}
