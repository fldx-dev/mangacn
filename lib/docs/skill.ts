import type { LoadedRegistry, LoadedRegistryItem } from "@/lib/registry";
import { registryItemUrl } from "@/lib/registry";
import { HOOKS_CATALOG } from "@/lib/registry/hooks";
import {
  BLOCKS_CATALOG,
  CATEGORY_LABELS,
  COMPONENTS_CATALOG,
  DOCS_SECTIONS,
  docItems,
  groupByCategory,
} from "./catalog";
import { docsUrl, installCommand, SITE_URL } from "./install-command";

/** Repo-relative folder of the Agent Skill (SPEC-agent-tooling §5); the MCP's `get_skill` reads it. */
export const SKILL_DIR = "skills/mangacn";

/** The generated catalog reference inside the skill. */
export const SKILL_CATALOG_PATH = `${SKILL_DIR}/references/catalog.md`;

export const SKILL_CATALOG_HEADER =
  "<!-- Generated by scripts/gen-skill.ts from the registry catalog. Do not edit; run `pnpm gen:skill`. -->";

/** The theme catalog's items in install order: what the foundation section lists first. */
const FOUNDATION_ORDER = [
  "theme",
  "font-display",
  "font-dialogue",
  "font-dialogue-ja",
  "ink-frame",
  "manga-motion",
];

/**
 * Where an agent reads about a theme-catalog item: the theme and its fonts on the theming
 * guide, the ink frame under its pen. An item with no page links its registry JSON.
 */
function foundationDocs(item: LoadedRegistryItem): string {
  if (item.type === "registry:theme") return docsUrl(item.name);
  if (item.type === "registry:font") return `${SITE_URL}/docs/theming#fonts`;
  if (item.name === "ink-frame") return `${SITE_URL}/docs/theming#the-pen`;
  return registryItemUrl(item.name);
}

function entry(name: string, description: string, docs: string): string[] {
  const ownPage = DOCS_SECTIONS.some((section) => docs.startsWith(`${SITE_URL}${section.url}/`));
  const markdown = ownPage ? ` (Markdown: ${docs}.md)` : "";
  return [
    `- \`${name}\`: ${description}`,
    `  Install: \`${installCommand(name, "npm")}\``,
    `  Docs: ${docs}${markdown}`,
  ];
}

/**
 * `skills/mangacn/references/catalog.md`: every registry item, the theme catalog first, then
 * the component catalog under `CATEGORIES` headings, then the blocks under "Blocks", then the
 * hooks under "Hooks", each with its one-line description, the npm install command and its docs
 * URL (a hook's registry JSON: it has no page).
 */
export function renderSkillCatalog(
  registry: LoadedRegistry,
  demos: readonly { item: string; demo: string }[],
): string {
  const foundation = registry.items
    .filter(
      (item) =>
        item.source !== COMPONENTS_CATALOG &&
        item.source !== BLOCKS_CATALOG &&
        FOUNDATION_ORDER.includes(item.name),
    )
    .sort((a, b) => FOUNDATION_ORDER.indexOf(a.name) - FOUNDATION_ORDER.indexOf(b.name));
  // Blocks carry the one category `block`, so they group under "Blocks" after the components.
  const components = [...docItems(registry, demos), ...docItems(registry, demos, BLOCKS_CATALOG)];
  // Hooks have no demos and no page, so they come from their catalog, not from docItems.
  const hooks = registry.items.filter((item) => item.source === HOOKS_CATALOG);
  const count = foundation.length + components.length + hooks.length;

  const lines = [
    SKILL_CATALOG_HEADER,
    "",
    "# mangacn catalog",
    "",
    `All ${count} items in the registry. Each line gives the item's name, what it is, the one`,
    "command that installs it (with ink-frame first when it draws an outline) and its docs.",
    "Swap `npx` for `pnpm dlx`, `yarn dlx` or `bunx --bun` to match the project, and keep the",
    "flags: `--overwrite` answers the overwrite question for a file already there, and `--yes`",
    "(on the theme's line) answers the theme's own prompt, so the command runs unattended",
    "(see install.md).",
    "",
    "A component page's Markdown (the `.md` URL) holds its props table and every demo's source:",
    "read it, or the MCP's `get_item`, before using a prop.",
    "",
    "## Foundation",
    "",
    "The theme, its fonts, the pen and the motion presets. Install the theme once per project.",
    "",
    ...foundation.flatMap((item) => entry(item.name, item.description ?? "", foundationDocs(item))),
  ];

  for (const [category, group] of groupByCategory(components)) {
    lines.push("", `## ${CATEGORY_LABELS[category]}`, "");
    for (const item of group) lines.push(...entry(item.name, item.description, docsUrl(item.name)));
  }

  if (hooks.length > 0) {
    lines.push(
      "",
      `## ${CATEGORY_LABELS.hook}`,
      "",
      "A hook installs with the item that needs it: that item declares it by URL, so its one add",
      "writes the hook to the project's hooks folder (`hooks/<name>.ts`) and the item imports it from",
      "`@/hooks/<name>`. Add a hook alone only to call it from your own components.",
      "",
    );
    for (const item of hooks) {
      lines.push(...entry(item.name, item.description ?? "", docsUrl(item.name)));
    }
  }

  return `${lines.join("\n")}\n`;
}
