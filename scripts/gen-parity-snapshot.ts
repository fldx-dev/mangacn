/**
 * Fetches the stock base-nova source of the restyled primitives (`PARITY_PRIMITIVES`) and of the
 * stock-derived blocks (`PARITY_BLOCKS`), and writes registry/ui/__parity__/base-nova.json and
 * registry/blocks/__parity__/base-nova.json, the snapshots registry/ui/parity.test.ts and
 * registry/blocks/parity.test.ts compare against (SPEC-components §4.1). Network only; never
 * runs in CI. Refreshing a snapshot after a shadcn release is a deliberate, reviewed change.
 *
 * Usage: pnpm gen:parity
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  BLOCK_PARITY_SNAPSHOT_PATH,
  type BlockParitySnapshot,
  extractBlockParityShape,
  extractParityShape,
  PARITY_BLOCKS,
  PARITY_PRIMITIVES,
  PARITY_SNAPSHOT_PATH,
  type ParitySnapshot,
  STOCK_ITEM_URL,
  sha1,
} from "../lib/registry/parity";
import { formatJson } from "../lib/registry/theme-preset-items";

interface StockItem {
  name: string;
  dependencies?: string[];
  registryDependencies?: string[];
  files: { path: string; type: string; target?: string; content: string }[];
}

const COMMENT =
  "Generated by scripts/gen-parity-snapshot.ts (pnpm gen:parity). Do not edit; refresh deliberately after a shadcn release.";

async function fetchStock(name: string): Promise<StockItem> {
  const url = STOCK_ITEM_URL.replace("{name}", name);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} → HTTP ${response.status}`);
  return (await response.json()) as StockItem;
}

function write(file: string, snapshot: object, count: number) {
  mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  // Each file as its check reads it, so a refresh that changes nothing upstream changes no byte:
  // the block snapshot is under Biome, which keeps short arrays on one line (formatJson does
  // the same; JSON.stringify broke each onto many lines); the primitives' snapshot is outside
  // Biome (biome.json) and has always been JSON.stringify's.
  const text =
    file === BLOCK_PARITY_SNAPSHOT_PATH ? formatJson(snapshot) : JSON.stringify(snapshot, null, 2);
  writeFileSync(path.resolve(file), `${text}\n`);
  console.log(`✓ wrote ${file} (${count} items)`);
}

async function main() {
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const snapshot: ParitySnapshot = {
    $comment: COMMENT,
    source: STOCK_ITEM_URL,
    fetchedAt,
    items: {},
  };
  const stock = await Promise.all(PARITY_PRIMITIVES.map(fetchStock));
  for (const item of stock) {
    if (item.files.length !== 1) {
      throw new Error(`${item.name}: expected one stock file, got ${item.files.length}`);
    }
    const content = item.files[0].content;
    snapshot.items[item.name] = { ...extractParityShape(content, item), sha1: sha1(content) };
  }
  write(PARITY_SNAPSHOT_PATH, snapshot, stock.length);

  const blocks: BlockParitySnapshot = {
    $comment: COMMENT,
    source: STOCK_ITEM_URL,
    fetchedAt,
    items: {},
  };
  const stockBlocks = await Promise.all(PARITY_BLOCKS.map(fetchStock));
  for (const item of stockBlocks) {
    const content = item.files.map((file) => file.content).join("\n");
    blocks.items[item.name] = {
      ...extractBlockParityShape(item.name, item.files, item),
      sha1: sha1(content),
    };
  }
  write(BLOCK_PARITY_SNAPSHOT_PATH, blocks, stockBlocks.length);
}

main().catch((error: Error) => {
  console.error(`✗ ${error.message}`);
  process.exit(1);
});
