/**
 * Fetches the stock base-nova source of the 21 restyled primitives and writes
 * registry/ui/__parity__/base-nova.json, the snapshot registry/ui/parity.test.ts compares
 * against (SPEC-components §4.1). Network only; never runs in CI. Refreshing the snapshot
 * after a shadcn release is a deliberate, reviewed change.
 *
 * Usage: pnpm gen:parity
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import {
  extractParityShape,
  PARITY_PRIMITIVES,
  PARITY_SNAPSHOT_PATH,
  type ParitySnapshot,
  STOCK_ITEM_URL,
  sha1,
} from "../lib/registry/parity";

interface StockItem {
  name: string;
  dependencies?: string[];
  registryDependencies?: string[];
  files: { path: string; content: string }[];
}

async function fetchStock(name: string): Promise<StockItem> {
  const url = STOCK_ITEM_URL.replace("{name}", name);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} → HTTP ${response.status}`);
  const item = (await response.json()) as StockItem;
  if (item.files.length !== 1) {
    throw new Error(`${name}: expected one stock file, got ${item.files.length}`);
  }
  return item;
}

async function main() {
  const snapshot: ParitySnapshot = {
    $comment:
      "Generated by scripts/gen-parity-snapshot.ts (pnpm gen:parity). Do not edit; refresh deliberately after a shadcn release.",
    source: STOCK_ITEM_URL,
    fetchedAt: new Date().toISOString().slice(0, 10),
    items: {},
  };
  const stock = await Promise.all(PARITY_PRIMITIVES.map(fetchStock));
  for (const item of stock) {
    const content = item.files[0].content;
    snapshot.items[item.name] = { ...extractParityShape(content, item), sha1: sha1(content) };
  }
  writeFileSync(path.resolve(PARITY_SNAPSHOT_PATH), `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`✓ wrote ${PARITY_SNAPSHOT_PATH} (${stock.length} items)`);
}

main().catch((error: Error) => {
  console.error(`✗ ${error.message}`);
  process.exit(1);
});
