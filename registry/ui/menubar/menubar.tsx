// Based on shadcn/ui Menubar (MIT, https://ui.shadcn.com), base-nova style, fetched 2026-11-09.
// Restyled for mangacn: the bar is one outlined paper strip (one InkFrame on the root) with a
// hand-drawn rule between triggers, the way toggle-group draws; triggers set in the display
// face. The menus are mangacn's dropdown-menu popup (heavy outline, ink highlight, hand-drawn
// separators), so the classes below only keep stock's sizes and turn its accent highlight ink.

/** One wobble for every bar's rules. */
const MENUBAR_SEED = 29;

function Menubar({ className, children, ...props }: MenubarPrimitive.Props) {
  return (
    <MenubarPrimitive
      data-slot="menubar"
      className={cn(
        "relative isolate flex h-9 items-center gap-2 rounded-lg border-0 bg-background p-[3px] has-[>[data-inked=true]]:bg-transparent!",
        className,
      )}
      {...props}
    >
      <InkFrame as="span" fill="paper" className="pointer-events-none absolute inset-0 -z-1" />
      {children}
    </MenubarPrimitive>
  );
}

function MenubarMenu({ ...props }: React.ComponentProps<typeof DropdownMenu>) {
  return <DropdownMenu data-slot="menubar-menu" {...props} />;
}

function MenubarGroup({ ...props }: React.ComponentProps<typeof DropdownMenuGroup>) {
  return <DropdownMenuGroup data-slot="menubar-group" {...props} />;
}

function MenubarPortal({ ...props }: React.ComponentProps<typeof DropdownMenuPortal>) {
  return <DropdownMenuPortal data-slot="menubar-portal" {...props} />;
}

function MenubarTrigger({
  className,
  children,
  ...props
}: React.ComponentProps<typeof DropdownMenuTrigger>) {
  return (
    <DropdownMenuTrigger
      data-slot="menubar-trigger"
      className={cn(
        "group/menubar-trigger relative flex items-center rounded-sm px-2 py-[2px] font-display text-base tracking-wide outline-hidden select-none hover:bg-muted focus-visible:bg-muted aria-expanded:bg-primary aria-expanded:text-primary-foreground",
        className,
      )}
      {...props}
    >
      {children}
      {/* The rule after this trigger, in the middle of the gap. The last trigger has none: last of
          its type, since an open menu may put focus guards after it. */}
      <InkFrame
        as="span"
        shape="line"
        fill="none"
        seed={MENUBAR_SEED}
        className="pointer-events-none absolute inset-y-0.5 -right-1 w-(--outline-width) translate-x-1/2 group-last-of-type/menubar-trigger:hidden"
      />
    </DropdownMenuTrigger>
  );
}

