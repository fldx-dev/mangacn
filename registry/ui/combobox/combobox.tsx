function ComboboxChips({
  className,
  children,
  ...props
}: React.ComponentPropsWithRef<typeof ComboboxPrimitive.Chips> & ComboboxPrimitive.Chips.Props) {
  return (
    <ComboboxPrimitive.Chips
      data-slot="combobox-chips"
      className={cn(
        "relative isolate flex min-h-8 flex-wrap items-center gap-1 rounded-lg border-0 bg-transparent bg-clip-padding px-2.5 py-1 text-sm transition-colors focus-within:ring-3 focus-within:ring-ring/50 has-aria-invalid:ring-3 has-aria-invalid:ring-destructive/20 has-aria-invalid:[--ink:var(--destructive)] has-data-[slot=combobox-chip]:px-1 dark:has-aria-invalid:ring-destructive/40",
        className,
      )}
      {...props}
    >
      {/* One outline for the field, as input-group draws it. */}
      <InkFrame as="span" className="pointer-events-none absolute inset-0 -z-1 rounded-lg" />
      {children}
    </ComboboxPrimitive.Chips>
  );
}

function ComboboxChip({
  className,
  children,
  showRemove = true,
  ...props
}: ComboboxPrimitive.Chip.Props & {
  showRemove?: boolean;
}) {
  return (
    <ComboboxPrimitive.Chip
      data-slot="combobox-chip"
      className={cn(
        "relative isolate flex h-[calc(--spacing(5.25))] w-fit items-center justify-center gap-1 rounded-sm border-0 px-1.5 text-xs font-medium whitespace-nowrap text-foreground has-disabled:pointer-events-none has-disabled:cursor-not-allowed has-disabled:opacity-50 has-data-[slot=combobox-chip-remove]:pr-0",
        className,
      )}
      {...props}
    >
      {/* An outlined paper chip. */}
      <InkFrame as="span" className="pointer-events-none absolute inset-0 -z-1 rounded-sm" />
      {children}
      {showRemove && (
        <ComboboxPrimitive.ChipRemove
          render={<Button variant="ghost" size="icon-xs" />}
          className="-ml-1 opacity-50 hover:opacity-100"
          data-slot="combobox-chip-remove"
        >
          <XIcon className="pointer-events-none" />
        </ComboboxPrimitive.ChipRemove>
      )}
    </ComboboxPrimitive.Chip>
  );
}

